import HearthEngine

/// The three projections the synthetic tier covers (Conformance corpus, D21).
public enum CorpusProjection: String, Sendable, CaseIterable {
    /// A (48, 28)-point diamond.
    case diamond48x28
    /// A 2:1 diamond.
    case diamond2to1
    /// An orthogonal grid.
    case orthogonal

    public var tileWidth: Int {
        switch self {
        case .diamond48x28: 48
        case .diamond2to1: 64
        case .orthogonal: 32
        }
    }

    public var tileHeight: Int {
        switch self {
        case .diamond48x28: 28
        case .diamond2to1: 32
        case .orthogonal: 32
        }
    }

    /// Whether the centre of pixel (`x`, `y`) lies inside the tile's footprint.
    public func covers(x: Int, y: Int) -> Bool {
        let w = tileWidth
        let h = tileHeight
        guard x >= 0, x < w, y >= 0, y < h else { return false }
        if self == .orthogonal {
            return true
        }
        // |dx| / (w / 2) + |dy| / (h / 2) <= 1 for the pixel centre, in integers.
        return abs(2 * x + 1 - w) * h + abs(2 * y + 1 - h) * w <= w * h
    }
}

public struct CorpusEntry: Sendable, Equatable {
    public let name: String
    public let image: PixelImage

    public init(name: String, image: PixelImage) {
        self.name = name
        self.image = image
    }

    public var textureID: TextureID { TextureID(name) }
}

/// The synthetic tier: generated by code, deterministically, with integer arithmetic only (E-CORPUS-1).
/// The repository holds no binary asset for it.
public enum SyntheticCorpus {
    /// Six saturated colours, ordered so neighbours in any row or column contrast.
    public static let saturated: [RGBA8] = [
        RGBA8(255, 0, 0), RGBA8(0, 255, 255), RGBA8(0, 255, 0), RGBA8(255, 0, 255), RGBA8(0, 0, 255), RGBA8(255, 255, 0),
    ]
    /// Six muted colours that white digits read on.
    public static let muted: [RGBA8] = [
        RGBA8(160, 40, 40), RGBA8(40, 160, 40), RGBA8(40, 40, 160), RGBA8(160, 160, 40), RGBA8(160, 40, 160),
        RGBA8(40, 160, 160),
    ]

    public static func flat(_ color: RGBA8, width: Int, height: Int) throws(EngineError) -> PixelImage {
        try PixelImage(width: width, height: height, filledWith: color)
    }

    /// `color` with alpha rising from 0 at the left edge to 255 at the right one.
    public static func alphaRamp(width: Int, height: Int, color: RGBA8 = .white) throws(EngineError) -> PixelImage {
        var image = try PixelImage(width: width, height: height, filledWith: color)
        for y in 0..<height {
            for x in 0..<width {
                image.set(x: x, y: y, to: RGBA8(color.r, color.g, color.b, ramp(x, width)))
            }
        }
        return image
    }

    /// Red rises left to right, green top to bottom, blue falls left to right.
    public static func colourRamp(width: Int, height: Int) throws(EngineError) -> PixelImage {
        var image = try PixelImage(width: width, height: height, filledWith: .black)
        for y in 0..<height {
            for x in 0..<width {
                let red = ramp(x, width)
                image.set(x: x, y: y, to: RGBA8(red, ramp(y, height), 255 - red))
            }
        }
        return image
    }

    /// A grid of `cell`-sized squares in saturated colours; every square differs from its four neighbours.
    public static func saturatedNeighbours(cell: Int, columns: Int, rows: Int) throws(EngineError) -> PixelImage {
        guard sides.contains(cell), sides.contains(columns), sides.contains(rows) else {
            throw .malformedAssetHeader(width: product(cell, columns), height: product(cell, rows), byteCount: 0)
        }
        var image = try PixelImage(width: cell * columns, height: cell * rows, filledWith: .black)
        for y in 0..<image.height {
            for x in 0..<image.width {
                image.set(x: x, y: y, to: saturated[(x / cell + 2 * (y / cell)) % saturated.count])
            }
        }
        return image
    }

    /// One tile of `projection`: its footprint in a muted colour chosen by `number`, the number in white digits,
    /// and transparent black outside the footprint.
    public static func numberedTile(_ number: Int, projection: CorpusProjection) throws(EngineError) -> PixelImage {
        var image = try PixelImage(width: projection.tileWidth, height: projection.tileHeight, filledWith: .clear)
        let ground = muted[Int(number.magnitude % UInt(muted.count))]
        for y in 0..<image.height {
            for x in 0..<image.width where projection.covers(x: x, y: y) {
                image.set(x: x, y: y, to: ground)
            }
        }
        draw(number, into: &image, originX: 0, originY: 0, width: image.width, height: image.height, scale: 2)
        return image
    }

    /// A sheet of `columns` by `rows` cells, numbered from 0 in row order, each with a one-pixel black border
    /// that the number never overwrites.
    public static func numberedSheet(
        columns: Int, rows: Int, cellWidth: Int, cellHeight: Int
    ) throws(EngineError) -> PixelImage {
        guard sides.contains(columns), sides.contains(rows), sides.contains(cellWidth), sides.contains(cellHeight) else {
            throw .malformedAssetHeader(
                width: product(columns, cellWidth), height: product(rows, cellHeight), byteCount: 0)
        }
        var image = try PixelImage(width: columns * cellWidth, height: rows * cellHeight, filledWith: .black)
        for row in 0..<rows {
            for column in 0..<columns {
                let index = row * columns + column
                for y in 1..<max(1, cellHeight - 1) {
                    for x in 1..<max(1, cellWidth - 1) {
                        image.set(x: column * cellWidth + x, y: row * cellHeight + y, to: muted[index % muted.count])
                    }
                }
                draw(
                    index, into: &image, originX: column * cellWidth, originY: row * cellHeight,
                    width: cellWidth, height: cellHeight, scale: 2, inset: 1)
            }
        }
        return image
    }

    /// The whole tier, in a fixed order.
    public static func generate() throws(EngineError) -> [CorpusEntry] {
        var entries = [
            CorpusEntry(name: "flat/white", image: try flat(.white, width: 8, height: 8)),
            CorpusEntry(name: "flat/black", image: try flat(.black, width: 8, height: 8)),
            CorpusEntry(name: "flat/red-half", image: try flat(RGBA8(255, 0, 0, 128), width: 8, height: 8)),
            CorpusEntry(name: "ramp/alpha", image: try alphaRamp(width: 256, height: 8)),
            CorpusEntry(name: "ramp/colour", image: try colourRamp(width: 64, height: 64)),
            CorpusEntry(name: "neighbours/saturated", image: try saturatedNeighbours(cell: 8, columns: 6, rows: 4)),
        ]
        for projection in CorpusProjection.allCases {
            for number in 0..<tilesPerProjection {
                entries.append(
                    CorpusEntry(
                        name: tileName(number, projection), image: try numberedTile(number, projection: projection)))
            }
        }
        entries.append(
            CorpusEntry(
                name: "sheet/numbered", image: try numberedSheet(columns: 4, rows: 2, cellWidth: 32, cellHeight: 32)))
        return entries
    }

    public static let tilesPerProjection = 9

    public static func tileName(_ number: Int, _ projection: CorpusProjection) -> String {
        "tile/\(projection.rawValue)/\(number)"
    }

    /// The tier as one byte string: per entry the name, the size and the pixels. Two generations must agree on it.
    public static func serialize(_ entries: [CorpusEntry]) -> [UInt8] {
        var out = [UInt8]()
        func append(_ value: Int) {
            let v = UInt32(truncatingIfNeeded: value)
            out += [UInt8(v & 0xff), UInt8((v >> 8) & 0xff), UInt8((v >> 16) & 0xff), UInt8(v >> 24)]
        }
        for entry in entries {
            let name = Array(entry.name.utf8)
            append(name.count)
            out += name
            append(entry.image.width)
            append(entry.image.height)
            out += entry.image.bytes
        }
        return out
    }

    // MARK: Pieces

    /// What one factor of an image's side may be. Factors are checked before they are multiplied, so no
    /// argument can overflow; the product is then checked by `PixelImage`.
    static let sides = 1...PixelImage.maximumDimension

    /// `a * b` for an error's text: clamped to the nearest representable value where it overflows.
    static func product(_ a: Int, _ b: Int) -> Int {
        let (value, overflow) = a.multipliedReportingOverflow(by: b)
        guard overflow else { return value }
        return (a < 0) == (b < 0) ? Int.max : Int.min
    }

    /// 0 at index 0, 255 at the last index, linear between; 255 for a single step.
    static func ramp(_ index: Int, _ count: Int) -> UInt8 {
        count > 1 ? UInt8(index * 255 / (count - 1)) : 255
    }

    /// 3x5 digits, one row per element, the most significant bit on the left.
    static let glyphs: [[UInt8]] = [
        [0b111, 0b101, 0b101, 0b101, 0b111], [0b010, 0b110, 0b010, 0b010, 0b111], [0b111, 0b001, 0b111, 0b100, 0b111],
        [0b111, 0b001, 0b111, 0b001, 0b111], [0b101, 0b101, 0b111, 0b001, 0b001], [0b111, 0b100, 0b111, 0b001, 0b111],
        [0b111, 0b100, 0b111, 0b101, 0b111], [0b111, 0b001, 0b001, 0b001, 0b001], [0b111, 0b101, 0b111, 0b101, 0b111],
        [0b111, 0b101, 0b111, 0b001, 0b111],
    ]

    /// Draws the magnitude of `number` in white, centred in the given box. Pixels outside the box shrunk by
    /// `inset` on every side, or outside the image, are dropped: a number never reaches a neighbouring cell.
    static func draw(
        _ number: Int, into image: inout PixelImage, originX: Int, originY: Int, width: Int, height: Int, scale: Int,
        inset: Int = 0
    ) {
        let columns = (originX + inset)..<max(originX + inset, originX + width - inset)
        let rows = (originY + inset)..<max(originY + inset, originY + height - inset)
        let digits = String(number.magnitude).compactMap { $0.wholeNumberValue }
        let textWidth = (digits.count * 4 - 1) * scale
        let left = originX + (width - textWidth) / 2
        let top = originY + (height - 5 * scale) / 2
        for (position, digit) in digits.enumerated() {
            for row in 0..<5 {
                for column in 0..<3 where glyphs[digit][row] & (0b100 >> UInt8(column)) != 0 {
                    for dy in 0..<scale {
                        for dx in 0..<scale {
                            let x = left + (position * 4 + column) * scale + dx
                            let y = top + row * scale + dy
                            if columns.contains(x), rows.contains(y) {
                                image.set(x: x, y: y, to: .white)
                            }
                        }
                    }
                }
            }
        }
    }
}
